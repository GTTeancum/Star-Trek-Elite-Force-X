"""Regenerate Elite Force's original Xbox MDR vertex programs with XDK 5558."""
from pathlib import Path
import os
import struct
import subprocess


def source_for(width):
    lines = [
        "xvs.1.1",
        "; v0 normal, v1 UV, v2 palette register addresses, v3..v6 weighted offsets",
    ]
    for index in range(width):
        offset = f"v{index + 3}"
        lines.append(f"mov a0.x, v2.{'xyzw'[index]}")
        for row, axis in enumerate("xyz"):
            lines.append(f"dp4 r2.{axis}, {offset}, c[a0.x+{row}]")
            lines.append(f"dp3 r3.{axis}, v0, c[a0.x+{row}]")
        if index == 0:
            lines += ["mov r0.xyz, r2", f"mul r1.xyz, r3, {offset}.w"]
        else:
            lines += ["add r0.xyz, r0, r2", f"mad r1.xyz, r3, {offset}.w, r1"]
    for row, axis in enumerate("xyzw"):
        lines.append(f"dph oPos.{axis}, r0, c{row}")
    lines += [
        "dp3 r2.x, r1, c4", "max r2.x, r2.x, c4.w", "mul r3.xyz, r2.x, c5",
        "add oD0.xyz, r3, c6", "mov oD0.w, c6.w", "mov oT0, v1",
    ]
    return "\n".join(lines) + "\n"


def generate(root, destination):
    work = root / "build/split-actor-shaders"
    work.mkdir(parents=True, exist_ok=True)
    assembler = Path("C:/XDK_5558/XDK/xbox/bin/xsasm.exe")
    env = dict(os.environ, TMP=str(work), TEMP=str(work))
    declarations = ["// Generated by scripts/build_split_actor_shaders.py with XDK 5558."]
    for width in range(1, 5):
        source = work / f"skin{width}.vsh"
        binary = work / f"skin{width}.xvu"
        source.write_text(source_for(width), encoding="ascii")
        subprocess.run([assembler, "/nologo", source, binary], env=env, cwd=work, check=True)
        data = binary.read_bytes()
        words = struct.unpack(f"<{len(data) // 4}I", data)
        declarations.append(f"static const DWORD gpuSkinProgram{width}[] = {{")
        for start in range(0, len(words), 6):
            row = words[start : start + 6]
            declarations.append("    " + ", ".join(f"0x{word:08x}" for word in row) + ",")
        declarations.append("};")
    destination.write_bytes(("\n".join(declarations) + "\n").encode("ascii"))


if __name__ == "__main__":
    repository = Path(__file__).resolve().parents[1]
    generate(repository, repository / "code/win32/stefx_gpu_skin_programs.h")
